# ------------------------------------------------- canonical label resolver

wal_label_sources <- function() {
  c("active_reviewed_registry", "stage07_canonical", "stage01_fallback",
    "entity_id_fallback")
}

# A registry is ACTIVE only when a human has adjudicated it and is named.
# This is deliberately stricter than the proposal contract.
wal_is_active_reviewed <- function(registry) {
  if (!is.data.frame(registry) || !nrow(registry)) return(FALSE)
  status <- if (is.null(registry$adjudication_status)) {
    rep(NA_character_, nrow(registry))
  } else tolower(trimws(as.character(registry$adjudication_status)))
  reviewer <- if (is.null(registry$reviewer)) rep(NA_character_, nrow(registry)) else
    trimws(as.character(registry$reviewer))
  label <- if (is.null(registry$reviewed_biological_label)) {
    rep(NA_character_, nrow(registry))
  } else trimws(as.character(registry$reviewed_biological_label))
  all(status %in% c("reviewed", "adjudicated", "active")) &&
    all(!is.na(reviewer) & nzchar(reviewer) & !tolower(reviewer) %in% c("na", "none")) &&
    all(!is.na(label) & nzchar(label))
}

# Resolve ONE biological display label per dataset + level + entity_id.
#
# Precedence:
#   1. an ACTIVE validated reviewed registry
#   2. the Stage-07 canonical / final automatic label
#   3. the Stage-01 ModuleLabel_Final, as a last resort
#   4. the entity id itself, so a label is never empty
#
# Historical labels are never discarded: they are returned alongside as
# provenance columns.
resolve_wgcna_display_label <- function(entities, reviewed = NULL,
                                        stage07 = NULL, stage01 = NULL) {
  if (!is.data.frame(entities)) {
    stop("entities must be a data frame.", call. = FALSE)
  }
  need <- c("dataset", "level", "entity_id")
  missing <- setdiff(need, names(entities))
  if (length(missing)) {
    stop("entities is missing required column(s): ",
         paste(missing, collapse = ", "), ".", call. = FALSE)
  }
  key <- function(d) paste(as.character(d$dataset), as.character(d$level),
                           as.character(d$entity_id), sep = "\r")
  k <- key(entities)

  lookup <- function(tbl, col) {
    out <- rep(NA_character_, length(k))
    if (is.null(tbl) || !nrow(tbl) || is.null(tbl[[col]])) return(out)
    tk <- key(tbl)
    idx <- match(k, tk)
    v <- trimws(as.character(tbl[[col]]))
    v[!nzchar(v)] <- NA_character_
    out[!is.na(idx)] <- v[idx[!is.na(idx)]]
    out
  }

  reviewed_active <- wal_is_active_reviewed(reviewed)
  reviewed_label <- if (reviewed_active) {
    lookup(reviewed, "reviewed_biological_label")
  } else rep(NA_character_, length(k))
  stage07_label <- lookup(stage07, "canonical_biological_label")
  if (all(is.na(stage07_label))) stage07_label <- lookup(stage07, "final_plot_label")
  stage01_label <- lookup(stage01, "ModuleLabel_Final")

  label <- reviewed_label
  source <- ifelse(!is.na(label), "active_reviewed_registry", NA_character_)
  take <- is.na(label) & !is.na(stage07_label)
  label[take] <- stage07_label[take]; source[take] <- "stage07_canonical"
  take <- is.na(label) & !is.na(stage01_label)
  label[take] <- stage01_label[take]; source[take] <- "stage01_fallback"
  take <- is.na(label)
  label[take] <- as.character(entities$entity_id)[take]
  source[take] <- "entity_id_fallback"

  confidence <- rep(NA_character_, length(k))
  if (reviewed_active && !is.null(reviewed$confidence)) {
    confidence <- lookup(reviewed, "confidence")
  }
  confidence[source != "active_reviewed_registry"] <- "automatic"

  data.frame(
    dataset = as.character(entities$dataset),
    level = as.character(entities$level),
    entity_id = as.character(entities$entity_id),
    canonical_display_label = label,
    canonical_label_source = source,
    canonical_label_confidence = confidence,
    Stage01_ModuleLabel_Final = stage01_label,
    Stage07_label = stage07_label,
    reviewed_label = reviewed_label,
    stringsAsFactors = FALSE
  )
}

# Hard invariant: one canonical display label per dataset + level + entity_id.
wal_assert_one_label_per_entity <- function(resolved,
                                            label_column = "canonical_display_label") {
  need <- c("dataset", "level", "entity_id", label_column)
  missing <- setdiff(need, names(resolved))
  if (length(missing)) {
    stop("Resolved label table is missing: ", paste(missing, collapse = ", "), ".",
         call. = FALSE)
  }
  k <- paste(resolved$dataset, resolved$level, resolved$entity_id, sep = "\r")
  split_labels <- split(as.character(resolved[[label_column]]), k)
  offenders <- names(split_labels)[
    vapply(split_labels, function(v) length(unique(v[!is.na(v)])) > 1L, logical(1))
  ]
  if (length(offenders)) {
    stop("The same dataset + entity resolves to more than one display label: ",
         paste(utils::head(gsub("\r", " / ", offenders), 5), collapse = "; "),
         ". A single artifact must never show two names for one entity.",
         call. = FALSE)
  }
  invisible(TRUE)
}

# ------------------------------------------------- hierarchy redundancy

.wal_norm_label <- function(x) {
  x <- tolower(trimws(as.character(x)))
  gsub("[^a-z0-9]+", " ", x)
}

# Flag a multi-module supermodule where the parent and >= 2 member modules
# carry effectively the same label. A REVIEW WARNING, never an automatic
# failure: sometimes a supermodule genuinely is its members.
wal_hierarchy_redundancy <- function(modules, supermodules,
                                     label_column = "proposed_final_label") {
  need_m <- c("dataset", "entity_id", "parent_entity_id", label_column)
  need_s <- c("dataset", "entity_id", label_column)
  for (nm in need_m) if (!nm %in% names(modules))
    stop("modules is missing ", nm, ".", call. = FALSE)
  for (nm in need_s) if (!nm %in% names(supermodules))
    stop("supermodules is missing ", nm, ".", call. = FALSE)

  out <- rep(NA_character_, nrow(supermodules))
  for (i in seq_len(nrow(supermodules))) {
    ds <- supermodules$dataset[[i]]; sm <- supermodules$entity_id[[i]]
    mem <- modules[modules$dataset == ds &
                     as.character(modules$parent_entity_id) == sm, , drop = FALSE]
    if (nrow(mem) < 2L) next
    parent <- .wal_norm_label(supermodules[[label_column]][[i]])
    same <- .wal_norm_label(mem[[label_column]]) == parent
    same[is.na(same)] <- FALSE
    if (sum(same) >= 2L) {
      out[[i]] <- paste0(
        "REVIEW: supermodule label matches ", sum(same), " of ", nrow(mem),
        " member modules (", paste(mem$entity_id[same], collapse = ", "),
        "); member names are not discriminative."
      )
    }
    # duplicate member names within one supermodule are also worth flagging
    dup <- .wal_norm_label(mem[[label_column]])
    dup_tab <- table(dup[nzchar(dup)])
    if (any(dup_tab >= 2L)) {
      repeated <- names(dup_tab)[dup_tab >= 2L]
      msg <- paste0("REVIEW: ", length(repeated),
                    " label(s) shared by multiple member modules of ", sm, ".")
      out[[i]] <- if (is.na(out[[i]])) msg else paste(out[[i]], msg)
    }
  }
  out
}

# ------------------------------------------------ final approval table

wal_approval_columns <- function() {
  c("dataset", "level", "entity_id", "parent_entity_id",
    "current_active_label", "proposed_final_label",
    "alternative_label_1", "alternative_label_2", "confidence",
    "evidence_class", "adjudication_action", "top_hubs_compact",
    "dominant_theme", "strongest_alternative_theme",
    "central_support_summary", "GO_support_summary", "contradiction_summary",
    "hierarchy_redundancy_warning", "bp_blind_spot_warning",
    "context_caveat", "rationale",
    "candidate_theme", "automatic_proposal_label", "algorithmic_evidence_class",
    "evidence_class_source",
    "recommended_for_activation", "human_decision")
}

# Activation readiness. Deliberately conservative: anything mixed, unresolved,
# peripheral or low-confidence is NOT recommended, regardless of how attractive
# the label reads.
wal_recommend_activation <- function(confidence, evidence_class, action) {
  conf <- tolower(trimws(as.character(confidence)))
  cls <- tolower(trimws(as.character(evidence_class)))
  act <- toupper(trimws(as.character(action)))
  blocked_class <- grepl("mixed|unresolved|peripheral", cls)
  blocked_action <- act %in% c("MIXED", "UNRESOLVED")
  blocked_keep <- act %in% "KEEP_ACTIVE_REVIEWED"
  conf %in% c("high", "moderate") & !blocked_class & !blocked_action & !blocked_keep
}

# Assemble the approval table. `human_decision` is always NA: approval is the
# reviewer's act, never this pipeline's.
wal_build_approval_table <- function(entities) {
  for (nm in c("dataset", "level", "entity_id")) {
    if (!nm %in% names(entities)) stop("entities is missing ", nm, ".", call. = FALSE)
  }
  out <- entities
  for (nm in wal_approval_columns()) {
    if (!nm %in% names(out)) out[[nm]] <- NA_character_
  }
  out$recommended_for_activation <- wal_recommend_activation(
    out$confidence, out$evidence_class, out$adjudication_action)
  out$human_decision <- NA_character_
  out$contract_version <- wal_contract_version()
  out[, c(wal_approval_columns(), "contract_version"), drop = FALSE]
}

