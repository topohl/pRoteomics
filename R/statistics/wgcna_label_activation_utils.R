# ------------------------------------- claims-table canonical label contract

# The WGCNA entity columns used by the biological claims table. The exported
# table names them wgcna_entity_id / wgcna_level; the intermediate collectors use
# module_or_supermodule_id / entity_level, so both spellings are accepted.
wal_claims_entity_columns <- function(claims = NULL) {
  candidates <- list(
    list(id = "wgcna_entity_id", level = "wgcna_level"),
    list(id = "module_or_supermodule_id", level = "entity_level")
  )
  if (is.null(claims)) return(candidates[[1]])
  for (cand in candidates) {
    if (all(unlist(cand) %in% names(claims))) return(cand)
  }
  candidates[[1]]
}

# Attach ONE canonical display label per dataset + WGCNA entity, plus the
# provenance columns. Rows that are not WGCNA entities are left untouched.
#
# No historical label is discarded: Stage01_ModuleLabel_Final, Stage06_label and
# Stage07_label are retained alongside so the submission artifact still records
# what each naming stage said.
attach_canonical_wgcna_display_label <- function(claims, reviewed_dir = NULL,
                                                 stage07_reader = NULL) {
  cols <- wal_claims_entity_columns(claims)
  if (!all(unlist(cols) %in% names(claims))) return(claims)

  is_entity <- !is.na(claims[[cols$id]]) & nzchar(trimws(as.character(claims[[cols$id]]))) &
    as.character(claims[[cols$level]]) %in% c("module", "supermodule")
  if (!any(is_entity)) {
    claims$canonical_display_label <- NA_character_
    claims$canonical_label_source <- NA_character_
    return(claims)
  }

  entities <- unique(data.frame(
    dataset = as.character(claims$dataset[is_entity]),
    level = as.character(claims[[cols$level]][is_entity]),
    entity_id = as.character(claims[[cols$id]][is_entity]),
    stringsAsFactors = FALSE
  ))

  reviewed <- NULL
  rd <- reviewed_dir %||% repo_path("config", "wgcna_labels")
  for (ds in unique(entities$dataset)) {
    p <- file.path(rd, paste0(ds, ".csv"))
    if (!file.exists(p)) next
    r <- utils::read.csv(p, stringsAsFactors = FALSE)
    r$dataset <- ds
    reviewed <- if (is.null(reviewed)) r else
      merge(reviewed, r, all = TRUE, sort = FALSE)
  }
  # Only an ACTIVE reviewed registry may be used. A proposal never qualifies.
  if (!is.null(reviewed) && !wal_is_active_reviewed(reviewed)) reviewed <- NULL

  stage07 <- NULL
  reader <- stage07_reader %||% function(ds) {
    p <- wgcna_interpretable_artifact("WGCNA_final_label_lookup.csv", ds)
    if (!file.exists(p)) return(NULL)
    utils::read.csv(p, stringsAsFactors = FALSE)
  }
  for (ds in unique(entities$dataset)) {
    lk <- reader(ds)
    if (is.null(lk) || !all(c("level", "entity_id") %in% names(lk))) next
    lab <- intersect(c("canonical_biological_label", "final_plot_label"), names(lk))[1]
    if (is.na(lab)) next
    z <- data.frame(dataset = ds, level = as.character(lk$level),
                    entity_id = as.character(lk$entity_id),
                    canonical_biological_label = as.character(lk[[lab]]),
                    stringsAsFactors = FALSE)
    stage07 <- if (is.null(stage07)) z else rbind(stage07, z)
  }

  stage01 <- NULL
  if ("ModuleLabel_Final" %in% names(claims)) {
    stage01 <- unique(data.frame(
      dataset = as.character(claims$dataset[is_entity]),
      level = as.character(claims[[cols$level]][is_entity]),
      entity_id = as.character(claims[[cols$id]][is_entity]),
      ModuleLabel_Final = as.character(claims$ModuleLabel_Final[is_entity]),
      stringsAsFactors = FALSE
    ))
    stage01 <- stage01[!duplicated(stage01[c("dataset", "level", "entity_id")]), ,
                       drop = FALSE]
  }

  resolved <- resolve_wgcna_display_label(entities, reviewed = reviewed,
                                          stage07 = stage07, stage01 = stage01)
  wal_assert_one_label_per_entity(resolved)

  k <- paste(as.character(claims$dataset), as.character(claims[[cols$level]]),
             as.character(claims[[cols$id]]), sep = "\r")
  rk <- paste(resolved$dataset, resolved$level, resolved$entity_id, sep = "\r")
  idx <- match(k, rk)
  pick <- function(col) {
    out <- rep(NA_character_, length(k))
    out[!is.na(idx)] <- as.character(resolved[[col]])[idx[!is.na(idx)]]
    out
  }
  claims$canonical_display_label <- pick("canonical_display_label")
  claims$canonical_label_source <- pick("canonical_label_source")
  claims$Stage01_ModuleLabel_Final <- pick("Stage01_ModuleLabel_Final")
  claims$Stage07_label <- pick("Stage07_label")
  if (!"Stage06_label" %in% names(claims)) {
    claims$Stage06_label <- if ("cleaned_biological_label" %in% names(claims)) {
      as.character(claims$cleaned_biological_label)
    } else NA_character_
  }
  claims
}

# Hard invariant for the submission artifact.
assert_one_canonical_label_per_wgcna_entity <- function(claims) {
  cols <- wal_claims_entity_columns(claims)
  if (!all(c(unlist(cols), "canonical_display_label") %in% names(claims))) {
    return(invisible(TRUE))
  }
  keep <- !is.na(claims$canonical_display_label)
  if (!any(keep)) return(invisible(TRUE))
  sub <- data.frame(
    dataset = as.character(claims$dataset[keep]),
    level = as.character(claims[[cols$level]][keep]),
    entity_id = as.character(claims[[cols$id]][keep]),
    canonical_display_label = as.character(claims$canonical_display_label[keep]),
    stringsAsFactors = FALSE
  )
  wal_assert_one_label_per_entity(sub)
}

