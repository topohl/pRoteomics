# Manual-adjudication support and canonical display-label resolution.
#
# WHAT THIS FILE IS FOR
#   1. One canonical resolver for the biological display label, so consumers
#      stop reinventing precedence and the same entity can never appear under
#      two names inside one artifact.
#   2. A hierarchy-redundancy detector, so a multi-module supermodule and its
#      members do not all carry the same name.
#   3. The final human-approval table, carrying the curated adjudication for
#      each entity with its evidence and an explicitly EMPTY human decision.
#
# NOTHING HERE ACTIVATES A LABEL. Activation requires a registry that is
# adjudication_status = "reviewed" AND names a real reviewer; the proposals
# generated by this pipeline can never satisfy that.

# `%||%` comes from the canonical R/null_coalescing.R, loaded via R/paths.R.

