.wal_compact <- function(x, n = 8L, width = 300L) {
  x <- as.character(x)
  x <- x[!is.na(x) & nzchar(x)]
  if (!length(x)) return("[none]")
  substr(paste(utils::head(x, n), collapse = "; "), 1L, width)
}

# One tidy row per group + module + attribute. Long format so a group can have
# any number of members; the workbook pivots it wide for side-by-side reading.
wal_module_comparison <- function(themes, hubs, go_all, go_core, go_top25,
                                  groups = wal_comparison_groups()) {
  out <- list()
  emit <- function(g, m, attr, val) {
    out[[length(out) + 1L]] <<- data.frame(
      comparison_group = g$group, dataset = g$dataset, module_id = m,
      colliding_automatic_label = g$collision, attribute = attr,
      value = val, stringsAsFactors = FALSE)
  }
  go_pick <- function(tbl, ds, m, onto, n = 6L) {
    if (is.null(tbl) || !nrow(tbl)) return("[none]")
    z <- tbl[tbl$dataset == ds & tbl$ModuleID == m & tbl$Ontology == onto, , drop = FALSE]
    if (!nrow(z)) return("[no significant term]")
    z <- z[order(z$p.adjust), , drop = FALSE]
    .wal_compact(sprintf("%s (p=%.1e)", z$Description, z$p.adjust), n)
  }
  theme_set <- function(ds, m, set, n = 5L) {
    z <- themes[themes$dataset == ds & themes$ModuleID == m &
                  themes$protein_set == set, , drop = FALSE]
    if (!nrow(z)) return("[no theme]")
    z <- z[order(z$best_p_adjust), , drop = FALSE]
    .wal_compact(sprintf("%s (n=%d, p=%.1e)", z$theme, z$n_supporting_go_terms,
                         z$best_p_adjust), n)
  }

  for (g in groups) {
    ds <- g$dataset
    # proteins supporting each member's leading theme, for the distinguishing pass
    lead_prots <- list()
    for (m in g$members) {
      z <- themes[themes$dataset == ds & themes$ModuleID == m &
                    themes$protein_set == "core_kME_0.6", , drop = FALSE]
      if (!nrow(z)) z <- themes[themes$dataset == ds & themes$ModuleID == m, , drop = FALSE]
      z <- z[order(z$best_p_adjust), , drop = FALSE]
      lead_prots[[m]] <- if (nrow(z)) {
        trimws(unlist(strsplit(as.character(z$contributing_hub_symbols[[1]]), "[;,/]")))
      } else character()
    }
    for (m in g$members) {
      h <- hubs[hubs$dataset == ds & hubs$ModuleID == m, , drop = FALSE]
      h <- h[order(h$rank), , drop = FALSE]
      emit(g, m, "top_25_hubs_with_abs_kME",
           .wal_compact(sprintf("%s(%.2f)", h$GeneSymbol, h$abs_kME), 25L, 600L))
      emit(g, m, "go_bp_themes_all", theme_set(ds, m, "all"))
      emit(g, m, "go_bp_themes_core_kME_0.6", theme_set(ds, m, "core_kME_0.6"))
      emit(g, m, "go_bp_themes_top_hub_25", theme_set(ds, m, "top_hub_25"))
      emit(g, m, "go_cc", go_pick(go_core, ds, m, "CC"))
      emit(g, m, "go_mf", go_pick(go_core, ds, m, "MF"))
      emit(g, m, "go_bp_top_terms_all_set", go_pick(go_all, ds, m, "BP"))
      emit(g, m, "go_bp_top_terms_top25_set", go_pick(go_top25, ds, m, "BP"))

      z <- themes[themes$dataset == ds & themes$ModuleID == m, , drop = FALSE]
      z <- z[order(z$best_p_adjust), , drop = FALSE]
      if (nrow(z)) {
        emit(g, m, "leading_theme", as.character(z$theme[[1]]))
        emit(g, m, "centrality_support_of_leading_theme",
             sprintf("top10_frac=%s; top25_frac=%s; median_abs_kME=%s; centrality_AUC=%s",
                     format(z$fraction_top10_contributing[[1]], digits = 2),
                     format(z$fraction_top25_contributing[[1]], digits = 2),
                     format(z$median_contributor_abs_kME[[1]], digits = 2),
                     format(z$contributor_centrality_auc[[1]], digits = 2)))
        emit(g, m, "proteins_supporting_leading_theme",
             .wal_compact(lead_prots[[m]], 15L, 400L))
        alt <- z[as.character(z$theme) != as.character(z$theme[[1]]), , drop = FALSE]
        emit(g, m, "strongest_alternative_theme",
             if (nrow(alt)) sprintf("%s (n=%d, p=%.1e)", alt$theme[[1]],
                                    alt$n_supporting_go_terms[[1]], alt$best_p_adjust[[1]])
             else "[none]")
      } else {
        emit(g, m, "leading_theme", "[no theme]")
        emit(g, m, "centrality_support_of_leading_theme", "[no theme]")
        emit(g, m, "proteins_supporting_leading_theme", "[none]")
        emit(g, m, "strongest_alternative_theme", "[none]")
      }
      others <- unique(unlist(lead_prots[setdiff(g$members, m)]))
      emit(g, m, "proteins_distinguishing_from_group",
           .wal_compact(setdiff(lead_prots[[m]], others), 15L, 400L))
      emit(g, m, "themes_unique_to_this_module_in_group",
           .wal_compact(setdiff(
             unique(themes$theme[themes$dataset == ds & themes$ModuleID == m]),
             unique(themes$theme[themes$dataset == ds &
                                   themes$ModuleID %in% setdiff(g$members, m)])), 6L))
    }
  }
  do.call(rbind, out)
}

# ---------------------------------------------------- BP blind-spot detector
#
# The Stage-15 theme layer is built from BP terms only. An entity whose biology
# is carried by CC or MF evidence can therefore be classed mixed/unresolved
# while the packet's own GO tables name it clearly. That is not a hypothetical:
# it is what mis-labelled neuropil m03 and soma m02/m06 before manual review.
#
# Advisory only, like the hierarchy check. It never changes a label; it tells a
# reviewer where the automatic classification had no way to see the evidence.
wal_bp_blind_spot <- function(rows, go_core, p_threshold = 1e-04) {
  out <- rep(NA_character_, nrow(rows))
  if (is.null(go_core) || !nrow(go_core)) return(out)
  lab <- tolower(paste(rows$proposed_final_label, rows$algorithmic_evidence_class))
  for (i in seq_len(nrow(rows))) {
    if (!grepl("mixed|unresolved", lab[[i]])) next
    z <- go_core[go_core$dataset == rows$dataset[[i]] &
                   go_core$ModuleID == rows$entity_id[[i]] &
                   go_core$Ontology %in% c("CC", "MF"), , drop = FALSE]
    if (!nrow(z)) next
    z <- z[order(z$p.adjust), , drop = FALSE]
    if (z$p.adjust[[1]] >= p_threshold) next
    out[[i]] <- sprintf(
      paste0("REVIEW: classed mixed/unresolved by a BP-only theme layer, but the ",
             "core set carries %d significant CC/MF terms led by '%s' (%s, p=%.1e). ",
             "Check whether the biology is simply not visible in BP."),
      nrow(z), z$Description[[1]], z$Ontology[[1]], z$p.adjust[[1]])
  }
  out
}

# ------------------------------------------- conservative unapproved proposals
#
# Safety rule for rows this pipeline is PROPOSING (not rows that already carry an
# active reviewed label). If a proposal is low confidence and therefore not
# recommended for activation, its PRIMARY wording must itself be conservative:
# a reviewer skimming the primary column must not read a specific mechanism that
# the evidence was too weak to activate.
#
# The specific theme is never lost. It moves to candidate_theme and to the
# alternative wording, so the evidence and the reading remain on the row.
#
# Rows with adjudication_action == "KEEP_ACTIVE_REVIEWED" are EXEMPT: those are
# human-reviewed labels already in force, and rewriting them here would be
# exactly the automatic registry edit the framework forbids.
wal_conservative_label <- function() "mixed / unresolved"

wal_is_conservative_label <- function(x) {
  tolower(trimws(as.character(x))) %in%
    c("mixed / unresolved", "mixed/unresolved", "unresolved", "")
}

wal_enforce_conservative_unapproved <- function(rows) {
  need <- c("proposed_final_label", "confidence", "adjudication_action")
  for (nm in need) if (!nm %in% names(rows))
    stop("rows is missing ", nm, ".", call. = FALSE)
  if (!"candidate_theme" %in% names(rows)) rows$candidate_theme <- NA_character_
  if (!"alternative_label_1" %in% names(rows)) rows$alternative_label_1 <- NA_character_
  if (!"alternative_label_2" %in% names(rows)) rows$alternative_label_2 <- NA_character_

  conf <- tolower(trimws(as.character(rows$confidence)))
  act <- toupper(trimws(as.character(rows$adjudication_action)))
  hit <- conf %in% "low" & !act %in% "KEEP_ACTIVE_REVIEWED" &
    !wal_is_conservative_label(rows$proposed_final_label)
  hit[is.na(hit)] <- FALSE
  if (!any(hit)) return(rows)

  demoted <- as.character(rows$proposed_final_label)[hit]
  rows$candidate_theme[hit] <- demoted
  # keep the demoted wording as the leading alternative, without losing an
  # existing alternative: shift it down if slot 2 is free.
  a1 <- as.character(rows$alternative_label_1)[hit]
  a2 <- as.character(rows$alternative_label_2)[hit]
  move <- (is.na(a2) | !nzchar(a2)) & !is.na(a1) & nzchar(a1) & a1 != demoted
  a2[move] <- a1[move]
  a1 <- demoted
  # an alternative that merely repeats the new conservative primary carries no
  # information for the reviewer, so drop it rather than display a duplicate.
  a2[wal_is_conservative_label(a2)] <- NA_character_
  rows$alternative_label_1[hit] <- a1
  rows$alternative_label_2[hit] <- a2
  rows$proposed_final_label[hit] <- wal_conservative_label()
  rows$adjudication_action[hit] <- "MIXED"
  rows$rationale[hit] <- paste0(
    "PRIMARY PROPOSAL HELD CONSERVATIVE. The evidence-based reading is retained in ",
    "candidate_theme and alternative_label_1, but the primary wording is '",
    wal_conservative_label(), "' because the adjudicated confidence is low and the ",
    "row is not recommended for activation. ", as.character(rows$rationale)[hit])
  rows
}
